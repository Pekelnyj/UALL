def main():
    p = DATA_DIR / "translations.json"
    t = json.loads(p.read_text(encoding="utf-8"))
    spells = t["spells"]
    dt = t["descTemplates"]

    applied, refs = 0, 0
    rename = {}
    for sid, new in APPLY.items():
        old = spells.get(sid)
        if isinstance(old, str) and old != new:
            rename[old] = new
            spells[sid] = new
            applied += 1

    # Посилання на назви в описах: «Стара назва» -> «Нова назва».
    for k in list(dt):
        v = dt[k]
        changed = False
        for old, new in rename.items():
            tok = "«" + old + "»"
            if tok in v:
                v = v.replace(tok, "«" + new + "»"); changed = True; refs += 1
        if changed:
            dt[k] = v

    p.write_text(json.dumps(t, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"Застосовано назв: {applied} | оновлено посилань в описах: {refs}")

    # HOLD-список для користувача
    lines = ["# Назви заклять — на ТВОЄ рішення (ревізор не застосовував)\n",
             "Формат: id | поточне → пропозиція | причина\n"]
    for sid, (old, new, why) in HOLD.items():
        lines.append(f"- `{sid}` | **{old}** → {new} | {why}")
    (DATA_DIR / "review" / "names_hold_for_user.md").write_text(
        "\n".join(lines), encoding="utf-8")
    print(f"HOLD (на рішення користувача): {len(HOLD)} -> names_hold_for_user.md")


if __name__ == "__main__":
    main()

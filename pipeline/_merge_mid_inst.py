added_i = 0
for iid, ua in INST_UA.items():
    en = inst.get(iid, {}).get("en")
    if en and en not in idt:
        idt[en] = ua; added_i += 1

# --- лор Sporefall (бос Rotmire 2711) ---
LORE_UA = {
 "2711": {"name": "Ротмайр",
          "desc": "Фунгаріани Спорепаду виплекали грибного велета, що виріс далеко "
                  "за межі свого природного циклу. Ротмайр — звір грубої сили, чиї "
                  "спори здатні прискорювати ріст довколишніх грибів, плодячи нові "
                  "небезпеки для необачних."}}
added_l = 0
for eid, v in LORE_UA.items():
    if eid in lore:
        journal[eid] = {"name": v["name"], "desc": v["desc"]}; added_l += 1

json.dump(tr, open("data/translations.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print(f"instanceDesc додано: {added_i} | лор-босів додано: {added_l}")

# -*- coding: utf-8 -*-
"""Описи інстансів 3 рейдів SL → instanceDesc[EN]=ua."""
import sys, json
sys.stdout.reconfigure(encoding="utf-8")
inst = json.load(open("data/jraid_sl_inst.json", encoding="utf-8-sig"))
tr = json.load(open("data/translations.json", encoding="utf-8-sig"))
idt = tr.setdefault("instanceDesc", {})

UA = {
 "1190": "Довго Сір Денатріус правив мешканцями Ревендрету, доки ті збирали аніму з "
         "пихатих душ. Та коли посуха й страх охопили Тіньокрай, Денатріус виявив свою "
         "справжню відданість. Кинувши виклик колишньому Володареві, шляхетний Принц "
         "Ренатал збирає нечисленних уцілілих союзників для відчайдушної місії — "
         "проникнути в Замок Натрія й скинути Денатріуса з трону.",
 "1193": "Цілі еони Тюремник був ув'язнений у Пащі. Тепер його незліченні армії "
         "множаться, а він розсуває її межі, щоб поглинути Орібос. Перед лицем знищення "
         "Болвар збирає останніх союзників, щоб увірватися в саме серце Торґасту й стати "
         "проти Тюремника там, де він наймогутніший.",
 "1195": "Тюремник прорвався в Гробницю — загадкове серце Тіньокраю. Якщо він "
         "заволодіє її первозданною силою, то перекроїть космос, поставивши Смерть на "
         "чільне місце. Поки Зоваал готується підкорити реальність, Захисники Азероту "
         "кидаються вперед, щоб його спинити. Чи переважить їхня рішучість його волю?",
}
added = 0
for iid, ua in UA.items():
    en = inst.get(iid, {}).get("en")
    if en and en not in idt:
        idt[en] = ua; added += 1
json.dump(tr, open("data/translations.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print(f"instanceDesc SL додано: {added}")

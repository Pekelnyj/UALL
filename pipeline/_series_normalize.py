# -*- coding: utf-8 -*-
"""Нормалізація розколотих renown-серій до канону (за домінантою бази + якістю).
Skulker НАВМИСНО виключено: «скрадливий» — легітимний прикметник, ризик зламати."""
import json, re, sys
from pathlib import Path
sys.stdout.reconfigure(encoding="utf-8")
P = Path("g:/Claude Code/WoWUkraine/data/translations.json")
tr = json.loads(P.read_text(encoding="utf-8-sig"))

# порядок: довші/відмінкові форми ПЕРШІ, щоб не лишити хвостів
RULES = [
    # Delver «Дослідник Глибин» → Глибинник (зберігаємо відмінок)
    ("Дослідникові Глибин", "Глибинникові"),
    ("Дослідників Глибин", "Глибинників"),
    ("Дослідника Глибин", "Глибинника"),
    ("Дослідник Глибин", "Глибинник"),
    # Drakewatcher → Дракоглядач (стем-заміна зберігає закінчення)
    ("Дракоспостерігач", "Дракоглядач"),
    ("Драконоглядач", "Дракоглядач"),
    ("Драконаглядач", "Дракоглядач"),
    ("Дракоаглядач", "Дракоглядач"),
    # Whimsydrake → Примхадракон
    ("Примхо-дракон", "Примхадракон"),
    ("Вімсідрейк", "Примхадракон"),
    # Ottuk → Оттук (Отук* → Оттук*; «Оттук» не містить підрядка «Отук»)
    ("Отук", "Оттук"),
    # Трек-фрази (унікальні)
    ("Осяваємо Шлях", "Світло на шляху"),
    ("Осяваючи Шлях", "Світло на шляху"),
    ("Осяяти Шлях", "Світло на шляху"),
    ("Поклик ловів", "Поклик Полювання"),
    ("Поклик Ловів", "Поклик Полювання"),
    ("Оздоблення Дому", "Оздоблення оселі"),
    ("Вірний клієнт", "Постійний Клієнт"),
    ("Вірний Клієнт", "Постійний Клієнт"),
    ("Лояльний клієнт", "Постійний Клієнт"),
    ("Лояльний Клієнт", "Постійний Клієнт"),
    ("Шоу має тривати", "Шоу мусить тривати"),
]
cnt = {}
def conv(s):
    for a, b in RULES:
        if a in s:
            cnt[a] = cnt.get(a, 0) + s.count(a)
            s = s.replace(a, b)
    return s
def walk(v):
    if isinstance(v, str): return conv(v)
    if isinstance(v, dict): return {k: walk(x) for k, x in v.items()}
    if isinstance(v, list): return [walk(x) for x in v]
    return v
tr = walk(tr)
P.write_text(json.dumps(tr, ensure_ascii=False, indent=1), encoding="utf-8")
print("замін за правилами:")
for k, v in sorted(cnt.items(), key=lambda x: -x[1]):
    print(f"  {k!r}: {v}")
print("разом:", sum(cnt.values()))

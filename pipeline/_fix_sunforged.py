# -*- coding: utf-8 -*-
"""Серія Sunforged: прибрати тавтологію й звести креслення з предметами.

ПРИЧИНА. «Сонце-КОВАНА КОВАЛЬСЬКА скринька» — масло масляне: «кований» і
«коваль» один корінь. Рішення власника (18.10): Sunforged -> «Сонцегартований»
(інший корінь «гарт», сенс збережено — сталь гартують у вогні).

ЗАОДНО. Та сама річ звалася по-різному в КРЕСЛЕННІ та в САМОМУ ПРЕДМЕТІ:
    Plans: … Toolbox            -> «скринька ковальських інструментів»
    … Toolbox                   -> «ковальська скринька з інструментами»
    Plans: … Leatherworker's Knife -> «ніж чинбаря»
    … Leatherworker's Knife        -> «чинбарський ніж»
Гравець читав у рецепті одне, а в сумці бачив інше. Зводимо до форми ПРЕДМЕТА.
Плюс дві форми самого прикметника (Сонцекований / Сонцекутий) і один рядок із
малої літери.

Запуск: python _fix_sunforged.py [--apply]
Далі:   python generate_db.py
"""
import io
import json
import sys

sys.stdout.reconfigure(encoding="utf-8")
from common import DATA_DIR

APPLY = "--apply" in sys.argv
P = DATA_DIR / "translations.json"
tr = json.loads(P.read_text(encoding="utf-8-sig"))

# довші фрази ПЕРШИМИ, інакше коротке правило з'їсть частину довгого
PAIRS = [
    ("Сонцекована скринька ковальських інструментів",
     "Сонцегартована ковальська скринька з інструментами"),
    ("Сонцекована ковальська скринька з інструментами",
     "Сонцегартована ковальська скринька з інструментами"),
    ("Сонцекований чинбарський набір інструментів",
     "Сонцегартований чинбарський набір інструментів"),
    ("Сонцековані інструменти чинбаря",
     "Сонцегартований чинбарський набір інструментів"),
    ("Сонцекований ковальський молот", "Сонцегартований ковальський молот"),
    ("Сонцекований чинбарський ніж", "Сонцегартований чинбарський ніж"),
    ("Сонцекований ніж чинбаря", "Сонцегартований чинбарський ніж"),
    ("Сонцекований білувальний ніж", "Сонцегартований білувальний ніж"),
    ("сонцекований ніж білувальника", "Сонцегартований білувальний ніж"),
    ("Сонцекований набір голок", "Сонцегартований набір голок"),
    ("Сонцекована кирка", "Сонцегартована кирка"),
    ("Сонцекований серп", "Сонцегартований серп"),
    # броня: дві форми прикметника зводимо до однієї
    ("Сонцекутий Нагрудник", "Сонцегартований Нагрудник"),
    ("Сонцекований Нагрудник", "Сонцегартований Нагрудник"),
    ("Сонцекуті Наручі", "Сонцегартовані Наручі"),
    ("Сонцековані Наручі", "Сонцегартовані Наручі"),
    # хвіст: будь-яка інша форма кореня в цій серії
    ("Сонцекутого", "Сонцегартованого"), ("Сонцекутий", "Сонцегартований"),
    ("Сонцекуті", "Сонцегартовані"), ("Сонцекута", "Сонцегартована"),
    # Флейвори стоять у ЗНАХІДНОМУ («Навчає виготовляти Сонцековану…»), і
    # перша версія таблиці їх не бачила — у ній були лише називні форми.
    ("Сонцековану скриньку ковальських інструментів",
     "Сонцегартовану ковальську скриньку з інструментами"),
    ("Сонцекованих", "Сонцегартованих"), ("Сонцекованим", "Сонцегартованим"),
    ("Сонцекованої", "Сонцегартованої"), ("Сонцековану", "Сонцегартовану"),
    ("Сонцекованого", "Сонцегартованого"), ("Сонцекований", "Сонцегартований"),
    ("Сонцекована", "Сонцегартована"), ("Сонцековані", "Сонцегартовані"),
    ("сонцекований", "сонцегартований"), ("сонцекована", "сонцегартована"),
    ("сонцековану", "сонцегартовану"),
]

changed = []
for sec, d in tr.items():
    if not isinstance(d, dict):
        continue
    for k, v in list(d.items()):
        if not isinstance(v, str) or "онцеко" not in v and "онцеку" not in v:
            continue
        new = v
        for a, b in PAIRS:
            new = new.replace(a, b)
        if new != v:
            changed.append((sec, k, v, new))
            if APPLY:
                d[k] = new

print(f"змінено рядків: {len(changed)}")
for sec, k, old, new in changed:
    print(f"  [{sec}] {k[:46]}\n     - {old[:72]}\n     + {new[:72]}")
if not APPLY:
    print("\nЧЕРНЕТКА — нічого не записано, додай --apply")
    sys.exit(0)
io.open(P, "w", encoding="utf-8", newline="\n").write(
    json.dumps(tr, ensure_ascii=False, indent=1))
print("translations.json записано")

# -*- coding: utf-8 -*-
"""Свіп боргів, що виплили на хвилях 12.1.5 (14.10).

Кожне правило — з ТАБЛИЦЕЮ ФОРМ, а не заміною підрядка: у трьох випадках
зміна зачіпає рід («Хмільний Фестиваль» чол. -> «Хмільне Свято» сер.), а в
одному — весь порядок слів («Чоботи Залізного Кігтя» -> «Залізокіготні
Чоботи») [[term-rename-spread-and-gender]].

Що зводимо і за яким доказом:
  Prize/Prized -> «Призов-»   «Викликий» — НЕ слово; хтось прочитав Prize як
                              challenge. Гейт: правимо лише там, де в АНГЛІЙСЬКОМУ
                              ключі є Prize; справжні «Виклики» (Challenges)
                              лишаються.
  Nokhud  -> Нохуд            86 проти 45/28/25
  Brewfest-> Хмільне Свято    70 проти 23/21/16/10/5/1
  mawrat  -> пащур            13 проти 5/4/4/3/2/2
  Ironclaw-> Залізокіготн-    9 проти 3/2/2/1
  Ula'tek -> не відмінюється  270 проти 15 (canon.json: жін., невідмінюване)
  Прокатися -> Прокотися      10 проти 6 (друкарська помилка)

Рядки секції broadcast сюди НЕ пишемо напряму: майстер — Broadcast.lua, і
_sync_broadcast_master затер би правку [[never-regex-edit-broadcast-lua]].
Для них складаємо окремий файл під _update_broadcast_values.py.

Запуск: python _sweep_1014.py [--apply]
"""
import io
import json
import re
import sys
from collections import Counter

sys.stdout.reconfigure(encoding="utf-8")
from common import DATA_DIR

APPLY = "--apply" in sys.argv
P = DATA_DIR / "translations.json"
BC_OUT = DATA_DIR / "tester_new" / "sweep_broadcast.json"
tr = json.loads(P.read_text(encoding="utf-8-sig"))

# ── таблиці форм ────────────────────────────────────────────────────────────
PAIRS = [
    # Brewfest: кожна форма -> та сама відмінкова комірка «Хмільного Свята»
    ("Хмільного Фестивалю", "Хмільного Свята"), ("Хмільного фестивалю", "Хмільного свята"),
    ("Хмільному Фестивалю", "Хмільному Святу"), ("Хмільному фестивалю", "Хмільному святу"),
    ("Хмільним Фестивалем", "Хмільним Святом"), ("Хмільним фестивалем", "Хмільним святом"),
    ("Хмільний Фестиваль", "Хмільне Свято"), ("Хмільний фестиваль", "Хмільне свято"),
    ("Хмільному Фестивалі", "Хмільному Святі"), ("Хмільному фестивалі", "Хмільному святі"),
    ("Свята Броварів", "Хмільного Свята"), ("Свято Броварів", "Хмільне Свято"),
    ("Святу Броварів", "Хмільному Святу"), ("Святом Броварів", "Хмільним Святом"),
    ("Святі Броварів", "Хмільному Святі"),
    ("Пивного Свята", "Хмільного Свята"), ("Пивне Свято", "Хмільне Свято"),
    ("Пивному Святу", "Хмільному Святу"), ("Пивним Святом", "Хмільним Святом"),
    ("Пивному Святі", "Хмільному Святі"), ("Пивного свята", "Хмільного свята"),
    ("Бровар-фесту", "Хмільного Свята"), ("Бровар-фест", "Хмільне Свято"),
    ("Фестивалю Пивоварів", "Хмільного Свята"), ("Фестиваль Пивоварів", "Хмільне Свято"),
    ("Бровфесту", "Хмільного Свята"), ("Бровфестом", "Хмільним Святом"),
    ("Бровфесті", "Хмільному Святі"), ("Бровфест", "Хмільне Свято"),
    # mawrat -> пащур (усі форми чоловічі, узгодження прикметника не міняється)
    ("пащопацюк", "пащур"), ("пащурощур", "пащур"), ("пащурок", "пащур"),
    ("пащещур", "пащур"), ("пацюків Пащі", "пащурів"), ("пацюка Пащі", "пащура"),
    ("пацюк Пащі", "пащур"), ("щурів Пащі", "пащурів"), ("щура Пащі", "пащура"),
    ("щур Пащі", "пащур"),
    ("велика пащуряча", "великий пащур"), ("колосальні пащурячі", "колосальні пащури"),
    # Ironclaw -> Залізокіготн-
    ("Карбовані Чоботи Залізного Кігтя", "Карбовані Залізокіготні Чоботи"),
    ("Сплав Залізного Пазура", "Залізокіготний Сплав"),
    ("Залізокогтева", "Залізокіготна"), ("Залізокогтевий", "Залізокіготний"),
    ("Залізнокіготн", "Залізокіготн"),
    # друкарська помилка
    ("Прокатися", "Прокотися"),
]
ROOTS = [("Нокгуд", "Нохуд"), ("Нокхуд", "Нохуд"), ("Нокуд", "Нохуд"),
         ("нокгуд", "нохуд"), ("нокхуд", "нохуд"), ("нокуд", "нохуд")]
ULATEK = re.compile(r"Ула'тек(?:а|у|ом|ові|і)\b")
PRIZE = [("Викликого", "Призового"), ("Викликому", "Призовому"),
         ("Викликим", "Призовим"), ("Викликий", "Призовий"),
         ("Виклика", "Призова"), ("Виклике", "Призове")]


# РЕГІСТР «свята» залежить від секції: назви предметів у нас Title Case, а
# назви заклять і репліки — реченнєві. Без цього з «Швидкий баран Бровфесту»
# виходив «Швидкий баран Хмільного Свята» — велика літера посеред назви.
LOWER_SECTIONS = {"spells", "npcNames", "broadcast", "gossip", "itemFlavors",
                  "descTemplates", "mountDescriptions", "scenario", "bookTexts",
                  "auraDescriptions", "bossAbilities", "subnames", "holidays"}
TITLE_SVIATO = re.compile(r"(Хмільн(?:е|ого|ому|им))\s+Свят(о|а|у|ом|і)")

# Записи, де ключ — числовий ID, тож англійського тексту в ключі немає.
# Англійську звірено з DB2 12.1.5 (SpellName) і creatures.json, див. звіт 14.10.
PRIZE_BY_ID = {
    "spells": {"1251690": ("Викликий індик", "Призовий індик")},
}


def fix(text, en_key, sec=""):
    out = text
    for a, b in PAIRS:
        out = out.replace(a, b)
    for a, b in ROOTS:
        out = out.replace(a, b)
    out = ULATEK.sub("Ула'тек", out)
    # «Викликий» правимо ЛИШЕ там, де англійський ключ справді про Prize
    if re.search(r"\bPrize", en_key, re.I):
        for a, b in PRIZE:
            out = out.replace(a, b)
    hit = PRIZE_BY_ID.get(sec, {}).get(en_key)
    if hit:
        out = out.replace(hit[0], hit[1])
    if sec in LOWER_SECTIONS:
        out = TITLE_SVIATO.sub(lambda m: m.group(1) + " свят" + m.group(2), out)
    return out


changed, bc_changes = [], {}
stats = Counter()
for sec, d in tr.items():
    if not isinstance(d, dict):
        continue
    for k, v in list(d.items()):
        if not isinstance(v, str):
            continue
        # для секцій за ID англійський ключ невідомий -> Prize-правило не вмикаємо
        new = fix(v, k if not k.isdigit() else "", sec)
        if new == v:
            continue
        stats[sec] += 1
        changed.append((sec, k, v, new))
        if sec == "broadcast":
            bc_changes[k] = new
        elif APPLY:
            d[k] = new

print(f"змінено рядків: {len(changed)} | за секціями: {dict(stats)}")
for sec, k, old, new in changed[:25]:
    print(f"  [{sec}] {k[:46]}\n     - {old[:96]}\n     + {new[:96]}")
print(f"\nіз них у broadcast (окремим файлом): {len(bc_changes)}")
if not APPLY:
    print("\nЧЕРНЕТКА — нічого не записано, додай --apply")
    sys.exit(0)
io.open(P, "w", encoding="utf-8", newline="\n").write(
    json.dumps(tr, ensure_ascii=False, indent=1))
print("translations.json записано (крім broadcast)")
if bc_changes:
    BC_OUT.parent.mkdir(parents=True, exist_ok=True)
    BC_OUT.write_text(json.dumps(bc_changes, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"broadcast -> {BC_OUT}\n   далі: python _update_broadcast_values.py \"{BC_OUT}\"")

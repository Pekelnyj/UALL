# -*- coding: utf-8 -*-
"""Skulker → Скрадач, ТІЛЬКИ в записах, де EN містить 'Skulker' (щоб не зачепити
прозовий «крадій»=злодій / прикметник «скрадливий»). Зберігаємо відмінки."""
import json, re, sys
from pathlib import Path
sys.stdout.reconfigure(encoding="utf-8")
P = Path("g:/Claude Code/WoWUkraine/data/translations.json")
tr = json.loads(P.read_text(encoding="utf-8-sig"))

# відмінкові форми всіх варіантів → Скрадач (довші перші)
MAP = [
    ("Скрадайлами", "Скрадачами"), ("Скрадайлові", "Скрадачеві"), ("Скрадайлом", "Скрадачем"),
    ("Скрадайлів", "Скрадачів"), ("Скрадайла", "Скрадача"), ("Скрадайлу", "Скрадачу"),
    ("Скрадайли", "Скрадачі"), ("Скрадайло", "Скрадач"),
    ("Скрадливцями", "Скрадачами"), ("Скрадливцеві", "Скрадачеві"), ("Скрадливцем", "Скрадачем"),
    ("Скрадливців", "Скрадачів"), ("Скрадливця", "Скрадача"), ("Скрадливцю", "Скрадачу"),
    ("Скрадливці", "Скрадачі"), ("Скрадливець", "Скрадач"),
    ("Скрадникові", "Скрадачеві"), ("Скрадниками", "Скрадачами"), ("Скрадником", "Скрадачем"),
    ("Скрадників", "Скрадачів"), ("Скрадника", "Скрадача"), ("Скраднику", "Скрадачу"),
    ("Скрадники", "Скрадачі"), ("Скрадник", "Скрадач"),
    ("Крадьком", "Скрадачем"), ("Крадька", "Скрадача"), ("Крадьку", "Скрадачу"), ("Крадько", "Скрадач"),
    ("Крадіями", "Скрадачами"), ("Крадієві", "Скрадачеві"), ("Крадієм", "Скрадачем"),
    ("Крадіїв", "Скрадачів"), ("Крадія", "Скрадача"), ("Крадію", "Скрадачу"),
    ("Крадії", "Скрадачі"), ("Крадій", "Скрадач"),
    # дрібний пре-існуючий одрук у цій родині: безщелепий → безщелепний
    ("Безщелепого", "Безщелепного"), ("Безщелепий", "Безщелепний"),
]

def conv(s):
    for a, b in MAP:
        s = s.replace(a, b)
    # евфонія: « з Скрадач...» → « зі Скрадач...»
    s = re.sub(r"(?<=[ \(])з Скрадач", "зі Скрадач", s)
    return s

changed = []
for bucket in ("itemNames", "npcNames", "renown", "quests", "spells", "uiTooltips"):
    d = tr.get(bucket, {})
    if not isinstance(d, dict):
        continue
    for k in list(d):
        if not (isinstance(k, str) and "kulker" in k):
            continue
        v = d[k]
        if isinstance(v, str):
            nv = conv(v)
            if nv != v:
                changed.append((k, v, nv)); d[k] = nv
        elif isinstance(v, dict):
            for fld in ("title", "description", "objectives", "progress", "completion"):
                if isinstance(v.get(fld), str):
                    nv = conv(v[fld])
                    if nv != v[fld]:
                        changed.append((f"{k}/{fld}", v[fld][:40], nv[:40])); v[fld] = nv

P.write_text(json.dumps(tr, ensure_ascii=False, indent=1), encoding="utf-8")
print(f"змінено записів: {len(changed)}")
for k, o, n in changed:
    print(f"  {k[:38]:38} «{o}» → «{n}»")

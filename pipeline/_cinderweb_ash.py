# -*- coding: utf-8 -*-
"""Cinderweb -> «попелястий» (загальновживане; «жарина» — раритет, заборонено)."""
import json
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
TR = Path("g:/Claude Code/WoWUkraine/data/translations.json")
tr = json.loads(TR.read_text(encoding="utf-8-sig"))

# істоти: «X Жаринної павутини» -> прикметник «Попелястий X»; павутина-місце -> «Попеляста павутина»
REPL = [
    ("Трутні Жаринної павутини", "Попелясті трутні"),
    ("Трутнів Жаринної павутини", "Попелястих трутнів"),
    ("Трутня Жаринної павутини", "Попелястого трутня"),
    ("Трутень Жаринної павутини", "Попелястий трутень"),
    ("Павучки Жаринної павутини", "Попелясті павучки"),
    ("Павучків Жаринної павутини", "Попелястих павучків"),
    ("Павучка Жаринної павутини", "Попелястого павучка"),
    ("Павучок Жаринної павутини", "Попелястий павучок"),
    ("Прядильниць Жаринної павутини", "Попелястих прядильників"),
    ("Прядильниці Жаринної павутини", "Попелясті прядильники"),
    ("Прядильницю Жаринної павутини", "Попелястого прядильника"),
    ("Прядильниця Жаринної павутини", "Попелястий прядильник"),
    ("Прядильників Жаринної павутини", "Попелястих прядильників"),
    ("Прядильники Жаринної павутини", "Попелясті прядильники"),
    ("Прядильника Жаринної павутини", "Попелястого прядильника"),
    ("Прядильник Жаринної павутини", "Попелястий прядильник"),
    # павутина-місце (відмінки) — лишається структурою
    ("Жаринною павутиною", "попелястою павутиною"),
    ("Жаринної павутини", "попелястої павутини"),
    ("Жаринну павутину", "попелясту павутину"),
    ("Жаринній павутині", "попелястій павутині"),
    ("Жаринна павутина", "Попеляста павутина"),
]

cnt = 0
def fix(s):
    global cnt
    for a, b in REPL:
        if a in s:
            cnt += s.count(a); s = s.replace(a, b)
    return s


def walk(v):
    if isinstance(v, str): return fix(v)
    if isinstance(v, dict): return {k: walk(x) for k, x in v.items()}
    if isinstance(v, list): return [walk(x) for x in v]
    return v


tr2 = walk(tr)
TR.write_text(json.dumps(tr2, ensure_ascii=False, indent=1), encoding="utf-8")
text = json.dumps(tr2, ensure_ascii=False)
print(f"Замін на «попелястий»: {cnt}")
print("залишок «Жаринн»:", len(re.findall(r"Жаринн", text)))
print("приклади:")
for k, v in tr2["journalSections"].items():
    if "Cinderweb" in k and len(v) < 60:
        print(f"  {k!r} -> {v!r}")

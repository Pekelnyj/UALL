def fix_str(s: str, counter: dict) -> str:
    for old, new in REPLACES:
        if old in s:
            counter[old] = counter.get(old, 0) + s.count(old)
            s = s.replace(old, new)
    return s


def walk(value, counter):
    if isinstance(value, str):
        return fix_str(value, counter)
    if isinstance(value, dict):
        return {k: walk(v, counter) for k, v in value.items()}
    if isinstance(value, list):
        return [walk(v, counter) for v in value]
    return value


def main():
    counter = {}
    p = DATA_DIR / "translations.json"
    t = json.loads(p.read_text(encoding="utf-8"))
    # ВАЖЛИВО: en-рядки не чіпаємо — лише українські значення.
    for section in ("quests", "spells", "questObjectives"):
        if section in t:
            t[section] = walk(t[section], counter)
    if "descTemplates" in t:
        for item in t["descTemplates"]:
            if isinstance(item, dict) and isinstance(item.get("ua"), str):
                item["ua"] = fix_str(item["ua"], counter)
    p.write_text(json.dumps(t, ensure_ascii=False, indent=1), encoding="utf-8")

    json_total = sum(counter.values())
    print(f"translations.json: {json_total} замін")

    lua_counter = {}
    for name in ("Quests.lua", "Spells.lua", "SpellDescriptions.lua",
                 "QuestObjectives.lua", "Items.lua"):
        fp = ADDON_DB / name
        if not fp.exists():
            continue
        src = fp.read_text(encoding="utf-8")
        # У Lua-файлах en теж присутній (ключі/поля en=) — заміняємо лише
        # кирилицю, тож en-рядки не постраждають: усі шаблони кириличні.
        fixed = fix_str(src, lua_counter)
        if fixed != src:
            fp.write_text(fixed, encoding="utf-8")
    print(f"Lua-бази: {sum(lua_counter.values())} замін")

    for old, n in sorted(counter.items(), key=lambda x: -x[1]):
        print(f"  {n:3}x {old}")


if __name__ == "__main__":
    main()

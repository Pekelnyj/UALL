# -*- coding: utf-8 -*-
"""Звести СЕРІЇ предметів до однієї форми перед злиттям хвилі 12.1.5.

НАВІЩО. Порція агента — це зріз абетки, а серія («Autumnal/Blushing/Mossy …
Witchwick») розкидана по 5–6 порціях. Кожен агент бачив лише свій шматок і
обирав форму чесно, але серія в грі лежить поруч у вітрині — гравець бачить
«Пояс Осіннього Відьмогнота» і «Чоботи Рум'яної Відьминої Свічки» в одному
списку. Зводимо ПІСЛЯ хвилі, за якорем у БАЗІ, а не за більшістю в хвилі.

Якорі:
  Witchwick  -> «Відьмогніт»  — mounts 3004 «Осінній Відьмогніт» (уже в базі);
  Hex (ім.)  -> «вроки»       — NpcNames «Володар вроків Малакрасс»;
  Brewfest   -> «Хмільне Свято» — holidays-канон (домінанта по всій базі);
  Lollibop   -> «Лупцяник»    — каламбур lollipop+bop, 2 з 4 форм у хвилі;
  Exorcised  -> «Екзорцизований» — прикметник замість звороту з двох слів.

НЕ робимо сліпого свопу підрядка: у «Відьминої Свічки» жіночий рід, і слідом
треба міняти прикметник кольору («Рум'яної» -> «Рум'яного»), інакше вийде
«Рум'яної Відьмогнота» [[term-rename-spread-and-gender]].

Запуск: python _normalize_items_wave.py [--apply]
"""
import json
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
from common import DATA_DIR

APPLY = "--apply" in sys.argv
B = DATA_DIR / "batches" / "items1215"

# (регекс, заміна, пояснення) — застосовуються по порядку
RULES = [
    # 1. Жіноча «Відьмина Свічка» -> чоловічий «Відьмогніт»; прикметник кольору
    #    у родовому жіночому «-ої» мусить стати чоловічим «-ого».
    (r"([А-ЯІЇЄҐ][а-яіїєґ']*)ої\s+Відьминої\s+Свічки", r"\1ого Відьмогнота",
     "Відьмина Свічка -> Відьмогніт (з родом прикметника)"),
    (r"Відьминої\s+Свічки", "Відьмогнота", "Відьмина Свічка -> Відьмогніт"),
    (r"Відьмина\s+Свічка", "Відьмогніт", "Відьмина Свічка -> Відьмогніт (наз.)"),
    # 2. ґ -> г за наявною формою бази
    (r"Відьмоґнот", "Відьмогнот", "Відьмоґніт -> Відьмогніт"),
    (r"Відьмоґніт", "Відьмогніт", "Відьмоґніт -> Відьмогніт"),
    # 3. Льодяник-* -> Лупцяник
    (r"Льодяник-(?:Бац|Бум|Бабах)", "Лупцяник", "Lollibop -> Лупцяник"),
    # 4. Exorcised: зворот -> прикметник
    (r"Очищений\s+Екзорцизмом", "Екзорцизований", "Exorcised -> Екзорцизований"),
    (r"Очищена\s+Екзорцизмом", "Екзорцизована", "Exorcised -> Екзорцизована"),
    # 5. Brewfest -> Хмільне Свято
    (r"Хмільного\s+Фестивалю", "Хмільного Свята", "Brewfest -> Хмільне Свято"),
    (r"Хмільний\s+Фестиваль", "Хмільне Свято", "Brewfest -> Хмільне Свято"),
    (r"Бровфесту", "Хмільного Свята", "Brewfest -> Хмільне Свято"),
    (r"Бровфест", "Хмільне Свято", "Brewfest -> Хмільне Свято"),
    # 6. Hex як іменник -> вроки (лише там, де в EN справді Hex)
    (r"Свічка\s+Чарів", "Свічка Вроків", "Hex -> вроки"),
    (r"Поножі\s+Зурочення", "Поножі Вроків", "Hex -> вроки"),
    (r"Маска\s+Прокляття", "Маска Вроків", "Hex -> вроки"),
]

GATE = {"Відьмогніт": "Witchwick", "Відьмогнот": "Witchwick",
        "Лупцяник": "Lollibop", "Екзорцизован": "Exorcis",
        "Хмільн": "Brewfest", "Вроків": "Hex"}

changed, files = [], {}
for f in sorted(B.glob("out_ictx_*.json")):
    d = json.loads(f.read_text(encoding="utf-8-sig"))
    dirty = False
    for en, v in d.items():
        if not isinstance(v, dict):
            continue
        for key in ("name", "flavor"):
            s = v.get(key)
            if not isinstance(s, str):
                continue
            new = s
            for rx, rep, why in RULES:
                # заміну робимо лише якщо англійський ключ справді з тієї серії
                need = GATE.get(rep.split()[0][:9]) or GATE.get(rep[:9])
                if need and not re.search(need, en, re.I):
                    continue
                new2 = re.sub(rx, rep, new)
                if new2 != new:
                    changed.append((f.name, en, new, new2, why))
                    new = new2
            if new != s:
                v[key] = new
                dirty = True
    if dirty:
        files[f] = d

print(f"змінено рядків: {len(changed)} у {len(files)} файлах")
for fn, en, old, new, why in changed[:30]:
    print(f"   [{fn[9:11]}] {en}\n       - {old}\n       + {new}   ({why})")
if not APPLY:
    print("\nЧЕРНЕТКА — нічого не записано, додай --apply")
    sys.exit(0)
for f, d in files.items():
    f.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
print(f"\nзаписано файлів: {len(files)}")

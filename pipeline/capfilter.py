# ── НЕАНГЛІЙСЬКИЙ КЛІЄНТ ────────────────────────────────────────────────
# Частина тестерів грає німецькою, а збирач бере текст таким, яким його
# показує гра. Такий ключ у англійського гравця не зматчиться НІКОЛИ:
# переклад до нього змарновано, рядок у грі лишається англійським.
# 12.09–13.09 у чергах знайшлося: 77 німецьких цілей, 32 підказки, 3 репліки
# і 33 імена істот, які німецький клієнт уже записав у датамайн як
# «англійські» («Schattenjäger Ty'jin», «Kräcka Einauge»); у базі лежало
# 23 перекладені німецькі репліки.
# Ознака — умляути/ß або службові слова, яких в англійському тексті гри
# немає. «Quest» сюди класти НЕ можна: воно англійське, і перша спроба з ним
# дала 900 фальшивок.
# Німецька БЕЗ умляутів теж трапляється: 13.09 усі 39 цілей у черзі були
# німецькими («Erfolge», «Sprecht mit Estulan.», «Der Leerensturm»), і
# правило з умляутами їх не бачило. Слова нижче перевірено на всій базі —
# нуль фальшивок. «Der» і «Die» свідомо НЕ включено: «Der'izu Helm» — назва
# предмета, «Der is nothing to say» — тролячий говір, «Die, mortal!» —
# звичайна англійська репліка.
FOREIGN_PATTERN = (
    r"[äöüÄÖÜß]|\b(Abbrechen|Zurueck|Fertig|besiegt|Euch|Eure|nicht|werden|"
    r"wurde|einem|einer|eines|durch|gegen|sowie|bereits|Gegenstand|erhalten|"
    r"abgeschlossen|Ehrt|Beute|Truhe|Schluessel|getoetet|gesammelt|entzuendet|"
    r"Das|Sprecht|Findet|Nehmt|Stellt|Springt|Erfolge|Beschreibung|Belohnungen|"
    r"Ausblenden|Weltquests|Metaquests|Nachbarschaft|Kampfhaustiere|"
    r"Schmiedekunst|Schriftrolle|Einmarsch|Leere|Schlund|durchsuchen|zerlegt|"
    r"katalysiert|rausgeworfen|ausgequetscht|bekommt|Leerensturm|Sturmwind|"
    r"nach|und|oder|zum|zur|ist|sind|wird|sich)\b")
RUNTIME.append((FOREIGN_PATTERN, "текст неанглійського клієнта"))
_FOREIGN = re.compile(FOREIGN_PATTERN)
# Тултіп групи в шукачі груп: мітки стилю гри й назви груп, що їх пишуть гравці.
# Збирач до 0.56.2 записував такий тултіп цілком — у базу потрапили «Relaxed» і
# назва групи «Chomu b ni» -> «Чому б ні» [[guild-names-never-translate]]. Новий
# збирач тултіпи груп пропускає; це правило — для старих файлів зборів.
RUNTIME.append((r"^(\d+\s+)?(Relaxed|Competitive|Carry Offered|Chomu b ni)$",
                "текст гравця з тултіпа групи"))
# Тултіп гільдійної групи з назвою гільдії посеред речення — перекладає шаблон
# у UIHooks, у чергу не пускаємо (перевіряє _check_guild_leak.py).
RUNTIME.append((r"are members of [^%]+\. Guild achievements"
                r"|composed of guild members of [^%]+\. Guild achievements",
                "назва гільдії в тултіпі гільдійної групи"))
_SERVICE = re.compile(r"^(Gossip-Hash=|Quest ID=)")


def is_foreign(text):
    """Рядок зібрано з неанглійського (німецького) клієнта."""
    return bool(text) and bool(_FOREIGN.search(text))


# ДВІЙНИК ІЗ ТОКЕНОМ — доказ, що не потребує списку ніків. Якщо, підставивши
# токен на місце одного слова, отримуємо ключ, який уже є в базі, — гніздо
# змінне, а слово в ньому підставлене ім'я гравця. Той самий принцип уже
# працює в гейті _check_playernames.py; тут він відсіює такі рядки ще в черзі.
# 13.09 у черзі реплік 115 рядків із 138 були саме такими: 88 «PLAYERNAME WAS
# TAGGED!» (ВЕЛИКИМИ, тож регекс ніків їх не бачив) і 27 запечених імен, для
# яких «{NAME}»-двійник у базі вже лежав.
# Гніздо може стояти одразу після кольорового коду («|cFFFF0000Shidoari|r»):
# там межі слова немає, і без альтернативи `(?<=|cXXXXXXXX)` двійник не ловився.
_SLOT = re.compile(r"(?:(?<=\|c[0-9A-Fa-f]{8})|(?<![\w'’{]))[A-ZÀ-Þ][\w'’À-ɏ]*(?![\w'’}])")


def token_twin(text, done, token="{NAME}"):
    """Слово, що стоїть у гнізді імені (є двійник із токеном у `done`), або None."""
    if not text or not done:
        return None
    for m in _SLOT.finditer(text):
        cand = text[:m.start()] + token + text[m.end():]
        if cand in done:
            return m.group(0)
    return None


def is_service(text):
    """Службовий відбиток самого аддона («Gossip-Hash=…», «Quest ID=…»).

    Окремо від повного RUNTIME, бо для балачок і реплік повний набір
    ризикований: правило «лінк-рядок» зносило б законну репліку з
    посиланням на предмет.
    """
    return bool(text) and bool(_SERVICE.search(text))


_RX = [(re.compile(p), why) for p, why in RUNTIME]


def why_runtime(text):
    """Повертає причину відсіву або None, якщо рядок придатний для бази."""
    for rx, why in _RX:
        if rx.search(text):
            return why
    return None


def split(items, key=lambda x: x):
    """(придатні, [(рядок, причина), ...]) — відсіяне повертаємо, а не ковтаємо."""
    good, dropped = [], []
    for it in items:
        why = why_runtime(key(it))
        if why:
            dropped.append((key(it), why))
        else:
            good.append(it)
    return good, dropped


def report(dropped, limit=6):
    if not dropped:
        return
    from collections import Counter
    c = Counter(why for _, why in dropped)
    print(f"  відсіяно рантайму: {len(dropped)}")
    for why, n in c.most_common(limit):
        print(f"    • {why}: {n}")
